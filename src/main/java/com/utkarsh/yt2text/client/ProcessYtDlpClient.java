package com.utkarsh.yt2text.client;

import com.utkarsh.yt2text.config.AppProperties;
import com.utkarsh.yt2text.exception.CaptionNotFoundException;
import com.utkarsh.yt2text.exception.Yt2TextException;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

import java.io.BufferedReader;
import java.io.File;
import java.io.InputStreamReader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.TimeUnit;
import java.util.stream.Stream;

@Component
public class ProcessYtDlpClient implements YtDlpClient {

    private static final Logger log = LoggerFactory.getLogger(ProcessYtDlpClient.class);
    private final AppProperties appProperties;

    public ProcessYtDlpClient(AppProperties appProperties) {
        this.appProperties = appProperties;
    }

    @Override
    public Optional<File> downloadSubtitles(String canonicalUrl, Path workDir) {
        String binary = appProperties.getYtDlp().getBinaryPath();
        int timeoutSeconds = appProperties.getYtDlp().getTimeoutSeconds();

        // Download English captions or auto-generated captions in vtt format
        List<String> command = List.of(
                binary,
                "--skip-download",
                "--write-subs",
                "--write-auto-subs",
                "--sub-lang", "en.*,en",
                "--sub-format", "vtt",
                "-o", workDir.resolve("caption.%(ext)s").toString(),
                canonicalUrl
        );

        log.info("Executing yt-dlp to fetch subtitles for {}", canonicalUrl);
        executeProcess(command, timeoutSeconds);

        // Find the downloaded subtitle file
        try (Stream<Path> stream = Files.list(workDir)) {
            Optional<Path> found = stream
                    .filter(p -> p.getFileName().toString().endsWith(".vtt"))
                    .findFirst();
            return found.map(Path::toFile);
        } catch (Exception e) {
            log.warn("Error scanning for subtitle file in {}", workDir, e);
            return Optional.empty();
        }
    }

    @Override
    public File downloadAudio(String canonicalUrl, Path workDir) {
        String binary = appProperties.getYtDlp().getBinaryPath();
        int timeoutSeconds = appProperties.getYtDlp().getTimeoutSeconds();

        Path audioOutput = workDir.resolve("audio.mp3");
        List<String> command = List.of(
                binary,
                "-x",
                "--audio-format", "mp3",
                "-o", audioOutput.toString(),
                canonicalUrl
        );

        log.info("Executing yt-dlp to extract audio for {}", canonicalUrl);
        executeProcess(command, timeoutSeconds);

        if (Files.exists(audioOutput)) {
            return audioOutput.toFile();
        }

        // Try to check if yt-dlp downloaded without converting to exact name
        try (Stream<Path> stream = Files.list(workDir)) {
            return stream.filter(p -> {
                String name = p.getFileName().toString();
                return name.endsWith(".mp3") || name.endsWith(".m4a") || name.endsWith(".webm") || name.endsWith(".opus");
            }).findFirst().map(Path::toFile)
            .orElseThrow(() -> new Yt2TextException("Error downloading audio: file was not generated by yt-dlp"));
        } catch (Exception e) {
            throw new Yt2TextException("Error downloading audio: " + e.getMessage(), e);
        }
    }

    private void executeProcess(List<String> command, int timeoutSeconds) {
        try {
            ProcessBuilder processBuilder = new ProcessBuilder(command);
            processBuilder.redirectErrorStream(true);
            Process process = processBuilder.start();

            StringBuilder output = new StringBuilder();
            try (BufferedReader reader = new BufferedReader(new InputStreamReader(process.getInputStream()))) {
                String line;
                while ((line = reader.readLine()) != null) {
                    output.append(line).append("\n");
                }
            }

            boolean finished = process.waitFor(timeoutSeconds, TimeUnit.SECONDS);
            if (!finished) {
                process.destroyForcibly();
                throw new Yt2TextException("Process timed out after " + timeoutSeconds + " seconds: " + command.get(0));
            }

            int exitCode = process.exitValue();
            if (exitCode != 0) {
                log.warn("Process exited with code {}: {}", exitCode, output);
            }
        } catch (Yt2TextException e) {
            throw e;
        } catch (Exception e) {
            throw new Yt2TextException("Failed to run executable (" + command.get(0) + "): " + e.getMessage(), e);
        }
    }
}


package com.utkarsh.yt2text.controller;

import com.utkarsh.yt2text.dto.ConvertResponse;
import com.utkarsh.yt2text.service.ConversionPipelineService;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.core.io.Resource;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.Map;

@RestController
public class ConversionController {

    private final ConversionPipelineService pipelineService;

    public ConversionController(ConversionPipelineService pipelineService) {
        this.pipelineService = pipelineService;
    }

    /**
     * Health check endpoint.
     */
    @GetMapping("/api/health")
    public ResponseEntity<Map<String, String>> health() {
        return ResponseEntity.ok(Map.of(
                "status", "UP",
                "service", "youtube-to-text",
                "version", "1.0.0"
        ));
    }

    /**
     * Preserves exact contract of FastAPI endpoint:
     * Accepts form parameter 'youtube_url'.
     */
    @PostMapping(value = "/api/convert", consumes = {
            MediaType.APPLICATION_FORM_URLENCODED_VALUE,
            MediaType.MULTIPART_FORM_DATA_VALUE
    })
    public ResponseEntity<ConvertResponse> convert(
            @RequestParam("youtube_url") String youtubeUrl
    ) {
        ConvertResponse response = pipelineService.process(youtubeUrl);
        return ResponseEntity.ok(response);
    }

    /**
     * Preserves exact download endpoint contract: GET /{filename}.
     * Safely serves files generated by the conversion pipeline.
     */
    @GetMapping(value = "/{filename}", produces = MediaType.TEXT_PLAIN_VALUE)
    public ResponseEntity<Resource> downloadFile(@PathVariable("filename") String filename) {
        byte[] data = pipelineService.getFileContent(filename);
        ByteArrayResource resource = new ByteArrayResource(data);

        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"" + filename + "\"")
                .contentType(MediaType.TEXT_PLAIN)
                .contentLength(data.length)
                .body(resource);
    }
}

